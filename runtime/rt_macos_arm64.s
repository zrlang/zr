#==============================================================================
# runtime/rt_macos_arm64.s — zr 语言运行时（macOS aarch64 / arm64, AT&T syntax）
#
# 与 x86-64 版一一对应：libc 薄封装。arm64 macOS 上 C 符号同样带一个
# 前导下划线（`write` → `_write`）。
#
# AAPCS64（Darwin）：参数 x0..x7，返回值 x0；
# 调用前无需 shadow space，但栈必须 16 字节对齐（bl 自身会保存 x30）。
#==============================================================================

    .section __TEXT,__text

#------------------------------------------------------------------------------
# zr_panic(msg, len) -> !
#   x0 = msg, x1 = len
# 写 stderr(fd=2)，退出码 99。
#------------------------------------------------------------------------------
    .globl _zr_panic
_zr_panic:
    stp     x29, x30, [sp, #-32]!
    mov     x29, sp
    str     x1, [sp, #16]       // 保护 len（write 可能改写 caller-save 寄存器）
    mov     x2, x1              // count = len
    mov     x1, x0              // buf = msg
    mov     x0, #2              // fd = stderr
    bl      _write
    mov     x0, #99             // panic exit code
    bl      _exit
    ldp     x29, x30, [sp], #32
    ret

#------------------------------------------------------------------------------
# zr_write(fd, buf, count) -> isize
#   x0=fd, x1=buf, x2=count
#------------------------------------------------------------------------------
    .globl _zr_write
_zr_write:
    b       _write

#------------------------------------------------------------------------------
# zr_read(fd, buf, count) -> isize
#------------------------------------------------------------------------------
    .globl _zr_read
_zr_read:
    b       _read

#------------------------------------------------------------------------------
# zr_open(path, mode) -> isize
#   x0 = path (NUL 结尾), x1 = mode（0=只读 1=写 2=追加）
#
# macOS 的 O_* 标志与 Linux 不同（O_CREAT = 0x200），这里统一成调用方的
# 0/1/2 语义：只读、写（截断）、追加。
#------------------------------------------------------------------------------
    .globl _zr_open
_zr_open:
    stp     x29, x30, [sp, #-16]!
    mov     x29, sp
    mov     x8, x1             // x8 = mode
    cmp     x8, 0
    b.eq    1f
    cmp     x8, 1
    b.eq    2f
    // 只读：O_RDONLY
    mov     x1, 0
    b       3f
1:
    // O_WRONLY | O_CREAT | O_TRUNC = 0x1 | 0x200 | 0x400
    mov     x1, 0x601
    b       3f
2:
    // O_WRONLY | O_CREAT | O_APPEND = 0x1 | 0x200 | 0x8
    mov     x1, 0x209
3:
    mov     x2, 0644           // mode
    bl      _open
    ldp     x29, x30, [sp], #16
    ret

#------------------------------------------------------------------------------
# zr_close(fd) -> i32
#   x0 = fd
#------------------------------------------------------------------------------
    .globl _zr_close
_zr_close:
    b       _close

#------------------------------------------------------------------------------
# zr_exit(code) -> !
#------------------------------------------------------------------------------
    .globl _zr_exit
_zr_exit:
    b       _exit

#------------------------------------------------------------------------------
# zr_alloc(size, align) -> *mut void
#   x0 = size, x1 = align（malloc 只用 size）
#------------------------------------------------------------------------------
    .globl _zr_alloc
_zr_alloc:
    b       _malloc

#------------------------------------------------------------------------------
# zr_dealloc(ptr, size, align)
#   x0 = ptr
#------------------------------------------------------------------------------
    .globl _zr_dealloc
_zr_dealloc:
    b       _free

#------------------------------------------------------------------------------
# zr_realloc(ptr, old_size, new_size, align) -> *mut void
#   x0 = ptr, x1 = old, x2 = new, x3 = align
#------------------------------------------------------------------------------
    .globl _zr_realloc
_zr_realloc:
    mov     x1, x2              // realloc(ptr, new_size)
    b       _realloc