/// 有函数体、且不是 `main` 的函数加 `z_` 前缀；`extern` 声明与 `main` 原名。
///
/// 与 `mir::mangled_symbol` 口径一致，保证 C 后端产出的符号和原生后端、
/// 运行时能对上。
fn c_func_name(func: &HirFunction) -> String {
    if func.body.is_none() || func.name == "main" {
        func.name.clone()
    } else {
        format!("z_{}", func.name)
    }
}

/// 只留前向声明的函数：`async`（协程体不能当普通 C 函数）与 `comptime`
/// （已在前端求值）。
fn skip_func(func: &HirFunction) -> bool {
    func.is_async || func.is_comptime
}

/// 表达式是否只能以语句形式出现（翻不成 C 表达式）。
fn is_stmt_like(kind: &ExprKind) -> bool {
    matches!(
        kind,
        ExprKind::If(..) | ExprKind::While(..) | ExprKind::Loop(..) | ExprKind::Block(..)
    )
}

fn enum_is_unit_only(e: &HirEnum) -> bool {
    e.variants
        .iter()
        .all(|v| matches!(v.payload, HirVariantPayload::Unit))
}

fn binop_to_c(op: BinaryOp) -> &'static str {
    match op {
        BinaryOp::Add => "+",
        BinaryOp::Sub => "-",
        BinaryOp::Mul => "*",
        BinaryOp::Div => "/",
        BinaryOp::Rem => "%",
        BinaryOp::BitAnd => "&",
        BinaryOp::BitOr => "|",
        BinaryOp::BitXor => "^",
        BinaryOp::Shl => "<<",
        BinaryOp::Shr => ">>",
        BinaryOp::Eq => "==",
        BinaryOp::Ne => "!=",
        BinaryOp::Lt => "<",
        BinaryOp::Gt => ">",
        BinaryOp::Le => "<=",
        BinaryOp::Ge => ">=",
        BinaryOp::And => "&&",
        BinaryOp::Or => "||",
        // 范围运算符在 `for` 脱糖后就没了，不该出现在运行期；兜底成 `+`。
        BinaryOp::Range | BinaryOp::RangeInclusive => "+",
    }
}

fn unop_to_c(op: UnaryOp) -> &'static str {
    match op {
        UnaryOp::Neg => "-",
        UnaryOp::Not => "!",
        UnaryOp::BitNot => "~",
        UnaryOp::Deref => "*",
        UnaryOp::AddrOf => "&",
    }
}

fn float_to_c(f: f64) -> String {
    if f.is_nan() {
        return "NAN".to_string();
    }
    if f.is_infinite() {
        return if f > 0.0 { "INFINITY" } else { "-INFINITY" }.to_string();
    }
    let s = format!("{}", f);
    // C 需要 `1.0` 这种浮点字面量；Rust 的 `{}` 对整数值只给 `1`。
    if s.contains('.') || s.contains('e') || s.contains('E') {
        s
    } else {
        format!("{}.0", s)
    }
}

/// 把字符串编成 C 字面量内容。不可打印字节用**三位八进制**转义——`\xHH`
/// 会贪婪吞掉后面的十六进制字符，八进制最多三位、无歧义。
fn escape_c_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for &b in s.as_bytes() {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b'\n' => out.push_str("\\n"),
            b'\r' => out.push_str("\\r"),
            b'\t' => out.push_str("\\t"),
            0x20..=0x7e => out.push(b as char),
            _ => {
                let _ = write!(out, "\\{:03o}", b);
            }
        }
    }
    out
}
