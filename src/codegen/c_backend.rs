//! C 后端：把 HIR 翻译成**单个 C 翻译单元**，供自举 / 没有原生后端的平台使用。
//!
//! 设计见 `future/bootstrap/c_backend.md`：C 是通用自举目标——任何平台都有 C
//! 编译器，"先把 zr 编成 C、再交给系统 C 编译器"绕开了"自举语言得先有个能编
//! 自己的编译器"这个鸡生蛋问题。范围按设计文档克制：一个翻译单元、保留符号名、
//! 引入标准头、前向声明所有函数。
//!
//! 覆盖的 HIR 子集：标量算术 / 比较 / 逻辑 / 位运算、直接与间接调用、`let` /
//! `var`、`if` / `while` / `loop` / `break` / `continue` / `return`、结构体
//! （含字面量与字段访问）、指针（取址 / 解引用 / 下标）、类型转换、`str`
//! （`{ptr, len}` 胖指针，映射成同布局的 `zr_str`）。
//!
//! **未覆盖**的构造（含载荷的枚举、元组、切片 / 数组值语义、闭包、`match`——
//! HIR 里 `ExprKind::Match` 已丢失绑定信息、协程 / `yield`、内联汇编）会降级成
//! 中性值 `0`，只保证"C 能编过"，不保证语义正确。这正是自举第一版的范围：
//! 先让简单程序能走通 HIR → C。
//!
//! 符号名与 MIR 一致：有函数体、且不是 `main` 的函数加 `z_` 前缀，`extern`
//! 声明与 `main` 保持原名——这样 C 后端产出的目标文件与原生后端、运行时对得上。

use crate::typeck::hir::{
    BinaryOp, DefId, ExprKind, HirBlock, HirEnum, HirExpr, HirFunction, HirLiteral, HirModule,
    HirStmt, HirTypeDef, HirVariantPayload, Ty, UnaryOp,
};
use std::fmt::Write;

/// C 后端。
///
/// 只持有对 HIR 的只读引用；所有发射都追加到调用方给的 `String` 里，避免
/// `&self` 与 `&mut self.out` 的借用纠缠。
pub struct CBackend<'a> {
    module: &'a HirModule,
}

impl<'a> CBackend<'a> {
    /// 把整个 HIR 模块翻译成一个 C 翻译单元的文本。
    pub fn translate(module: &'a HirModule) -> String {
        let backend = CBackend { module };
        let mut out = String::new();
        backend.emit_prelude(&mut out);
        backend.emit_types(&mut out);
        backend.emit_statics(&mut out);
        backend.emit_func_prototypes(&mut out);
        backend.emit_funcs(&mut out);
        out
    }

    /// 头部：标准头 + `str` 的胖指针结构体。
    fn emit_prelude(&self, out: &mut String) {
        out.push_str("/* Generated by the zr C backend. Do not edit. */\n");
        out.push_str("#include <stdint.h>\n");
        out.push_str("#include <stddef.h>\n");
        out.push_str("#include <stdbool.h>\n");
        out.push_str("#include <stdlib.h>\n");
        out.push_str("#include <string.h>\n");
        out.push_str("#include <math.h>\n\n");
        // zr 的 `str` 是 `{ptr, len}` 胖指针，映射成同布局的结构体，于是
        // `s.ptr` / `s.len` 能直接翻成 C 的字段访问。
        out.push_str("typedef struct { const uint8_t *ptr; uintptr_t len; } zr_str;\n\n");
    }

    // ==================================================================
    // 类型定义
    // ==================================================================

    /// 发射枚举 / 结构体 / 联合体定义。
    ///
    /// 顺序有讲究：C 不能前置声明 `enum`，所以**枚举先出完整定义**（这样结构体
    /// 里的枚举字段是完整类型）；结构体 / 联合体先统一前置声明（允许相互引用
    /// 指针），再出完整定义。
    fn emit_types(&self, out: &mut String) {
        // `HashMap` 迭代顺序不确定，按 DefId 排序保证输出可复现。
        let mut ids: Vec<DefId> = self.module.type_defs.keys().copied().collect();
        ids.sort_by_key(|id| id.0);

        for id in &ids {
            if let Some(HirTypeDef::Enum(e)) = self.module.type_defs.get(id) {
                // 只有全 unit 变体才映射成 C 枚举。枚举名作前缀避免不同枚举的
                // 同名变体在 C 的全局枚举器命名空间里撞车。
                if enum_is_unit_only(e) {
                    let _ = writeln!(out, "enum {} {{", e.name);
                    for v in &e.variants {
                        let _ = writeln!(out, "    {}_{} = {},", e.name, v.name, v.discriminant);
                    }
                    let _ = writeln!(out, "}};\n");
                }
            }
        }
        for id in &ids {
            match self.module.type_defs.get(id) {
                Some(HirTypeDef::Struct(s)) => {
                    let _ = writeln!(out, "struct {};", s.name);
                }
                Some(HirTypeDef::Union(u)) => {
                    let _ = writeln!(out, "union {};", u.name);
                }
                _ => {}
            }
        }
        for id in &ids {
            match self.module.type_defs.get(id) {
                Some(HirTypeDef::Struct(s)) => {
                    let _ = writeln!(out, "struct {} {{", s.name);
                    for f in &s.fields {
                        let ft = self.ty_to_c(&f.ty);
                        let _ = writeln!(out, "    {} {};", ft, f.name);
                    }
                    let _ = writeln!(out, "}};\n");
                }
                Some(HirTypeDef::Union(u)) => {
                    let _ = writeln!(out, "union {} {{", u.name);
                    for f in &u.fields {
                        let ft = self.ty_to_c(&f.ty);
                        let _ = writeln!(out, "    {} {};", ft, f.name);
                    }
                    let _ = writeln!(out, "}};\n");
                }
                _ => {}
            }
        }
    }

    /// 全局 `static`：标量 + 初值可折叠才有数据符号（与 MIR 同口径）。
    fn emit_statics(&self, out: &mut String) {
        let mut any = false;
        for st in &self.module.statics {
            let Some(lit) = &st.const_value else { continue };
            let ty = self.ty_to_c(&st.ty);
            let init = self.literal_to_c(lit);
            let _ = writeln!(out, "static {} {} = {};", ty, st.name, init);
            any = true;
        }
        if any {
            out.push('\n');
        }
    }

    // ==================================================================
    // 函数
    // ==================================================================

    /// 前向声明所有已发射的函数，允许函数体里调用后面才定义的函数。
    fn emit_func_prototypes(&self, out: &mut String) {
        for func in &self.module.functions {
            if skip_func(func) {
                continue;
            }
            let ret = self.ret_ty_to_c(&func.return_type);
            let name = c_func_name(func);
            let params = self.params_to_c(func);
            let _ = writeln!(out, "{} {}({});", ret, name, params);
        }
        out.push('\n');
    }

    /// 发射函数体。`extern` 声明（无函数体）、`async` / `comptime` 函数只留
    /// 前向声明——它们要么由外部提供，要么已经被前端处理掉。
    fn emit_funcs(&self, out: &mut String) {
        let mut emitted: Vec<String> = Vec::new();
        for func in &self.module.functions {
            if skip_func(func) {
                continue;
            }
            let Some(body) = &func.body else { continue };
            let name = c_func_name(func);
            // 同名（用户定义 + 标准库定义）会撞成同一个符号：保留首个，
            // 跳过被遮蔽的——与 MIR 去重口径一致，否则 C 报重复定义。
            if emitted.contains(&name) {
                continue;
            }
            emitted.push(name.clone());

            let ret = self.ret_ty_to_c(&func.return_type);
            let params = self.params_to_c(func);
            let _ = writeln!(out, "{} {}({}) {{", ret, name, params);
            self.emit_block_stmts(out, body, 1);
            self.emit_block_tail(out, body, 1, true);
            let _ = writeln!(out, "}}\n");
        }
    }

    /// 返回值类型：`()` / `!` 映射成 `void`。
    fn ret_ty_to_c(&self, ty: &Ty) -> String {
        match ty {
            Ty::Unit | Ty::Never => "void".to_string(),
            _ => self.ty_to_c(ty),
        }
    }

    /// 形参列表：无参写成 `void`（C 的空参列表在定义里表示"参数未指定"，
    /// 必须显式 `void`）。
    fn params_to_c(&self, func: &HirFunction) -> String {
        if func.params.is_empty() {
            return "void".to_string();
        }
        func.params
            .iter()
            .map(|p| format!("{} local_{}", self.ty_to_c(&p.ty), p.local.0))
            .collect::<Vec<_>>()
            .join(", ")
    }

    // ==================================================================
    // 语句
    // ==================================================================

    fn emit_block_stmts(&self, out: &mut String, block: &HirBlock, indent: usize) {
        for stmt in &block.stmts {
            self.emit_stmt(out, stmt, indent);
        }
    }

    /// 块尾表达式。
    ///
    /// `as_return` 为真（函数体）时，非 `()` / `!` 的尾表达式翻成 `return`；
    /// 否则按语句位置处理（丢弃结果）。控制流构造必须走语句形式——它们翻不成
    /// C 表达式。
    fn emit_block_tail(&self, out: &mut String, block: &HirBlock, indent: usize, as_return: bool) {
        let Some(tail) = &block.tail else { return };
        let pad = "    ".repeat(indent);
        if as_return && !matches!(tail.ty, Ty::Unit | Ty::Never) && !is_stmt_like(&tail.kind) {
            let s = self.expr_to_c(tail);
            let _ = writeln!(out, "{}return {};", pad, s);
            return;
        }
        self.emit_expr_stmt(out, tail, indent);
    }

    fn emit_stmt(&self, out: &mut String, stmt: &HirStmt, indent: usize) {
        let pad = "    ".repeat(indent);
        match stmt {
            // `HirStmt::Let` 不携带类型：声明类型取自初始化表达式的类型。
            // 未初始化的 `let x;`（罕见）退回 `intptr_t`。
            HirStmt::Let { local, init } | HirStmt::Var { local, init } => {
                let name = format!("local_{}", local.0);
                match init {
                    Some(e) => {
                        let ty = self.ty_to_c(&e.ty);
                        let value = self.expr_to_c(e);
                        let _ = writeln!(out, "{}{} {} = {};", pad, ty, name, value);
                    }
                    None => {
                        let _ = writeln!(out, "{}intptr_t {};", pad, name);
                    }
                }
            }
            HirStmt::Expr(e) => self.emit_expr_stmt(out, e, indent),
            HirStmt::Item => {}
        }
    }

    /// 语句位置的表达式。
    ///
    /// 控制流（`if` / `while` / `loop` / 块）翻成 C 语句；`return` / `break` /
    /// `continue` / 赋值也在这里处理；其余按 `expr;` 发射。
    fn emit_expr_stmt(&self, out: &mut String, expr: &HirExpr, indent: usize) {
        let pad = "    ".repeat(indent);
        match &expr.kind {
            ExprKind::If(cond, then_block, else_block) => {
                let c = self.expr_to_c(cond);
                let _ = writeln!(out, "{}if ({}) {{", pad, c);
                self.emit_block_stmts(out, then_block, indent + 1);
                self.emit_block_tail(out, then_block, indent + 1, false);
                match else_block {
                    Some(el) => {
                        let _ = writeln!(out, "{}}} else {{", pad);
                        self.emit_block_stmts(out, el, indent + 1);
                        self.emit_block_tail(out, el, indent + 1, false);
                        let _ = writeln!(out, "{}}}", pad);
                    }
                    None => {
                        let _ = writeln!(out, "{}}}", pad);
                    }
                }
            }
            ExprKind::While(_label, cond, body) => {
                let c = self.expr_to_c(cond);
                let _ = writeln!(out, "{}while ({}) {{", pad, c);
                self.emit_block_stmts(out, body, indent + 1);
                self.emit_block_tail(out, body, indent + 1, false);
                let _ = writeln!(out, "{}}}", pad);
            }
            ExprKind::Loop(_label, body) => {
                let _ = writeln!(out, "{}while (1) {{", pad);
                self.emit_block_stmts(out, body, indent + 1);
                self.emit_block_tail(out, body, indent + 1, false);
                let _ = writeln!(out, "{}}}", pad);
            }
            ExprKind::Block(body) => {
                let _ = writeln!(out, "{}{{", pad);
                self.emit_block_stmts(out, body, indent + 1);
                self.emit_block_tail(out, body, indent + 1, false);
                let _ = writeln!(out, "{}}}", pad);
            }
            ExprKind::Return(value) => match value {
                Some(v) => {
                    let s = self.expr_to_c(v);
                    let _ = writeln!(out, "{}return {};", pad, s);
                }
                None => {
                    let _ = writeln!(out, "{}return;", pad);
                }
            },
            // `break value`（`loop` 带值）在 C 里没有直接对应，值被丢弃。
            ExprKind::Break(..) => {
                let _ = writeln!(out, "{}break;", pad);
            }
            ExprKind::Continue(_) => {
                let _ = writeln!(out, "{}continue;", pad);
            }
            ExprKind::Assign(target, value) => {
                let t = self.expr_to_c(target);
                let v = self.expr_to_c(value);
                let _ = writeln!(out, "{}{} = {};", pad, t, v);
            }
            _ => {
                let s = self.expr_to_c(expr);
                let _ = writeln!(out, "{}{};", pad, s);
            }
        }
    }

    // ==================================================================
    // 表达式
    // ==================================================================

    fn expr_to_c(&self, expr: &HirExpr) -> String {
        match &expr.kind {
            ExprKind::Literal(lit) => self.literal_to_c(lit),
            ExprKind::Local(id) => format!("local_{}", id.0),
            ExprKind::Def(id) => self.def_ref_to_c(*id),
            ExprKind::Binary(op, lhs, rhs) => format!(
                "({} {} {})",
                self.expr_to_c(lhs),
                binop_to_c(*op),
                self.expr_to_c(rhs)
            ),
            ExprKind::Unary(op, operand) => {
                format!("({}{})", unop_to_c(*op), self.expr_to_c(operand))
            }
            ExprKind::Assign(target, value) => {
                format!("({} = {})", self.expr_to_c(target), self.expr_to_c(value))
            }
            ExprKind::Call { callee, args, .. } => {
                let head = self.def_ref_to_c(*callee);
                let args = args
                    .iter()
                    .map(|a| self.expr_to_c(a))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("{}({})", head, args)
            }
            ExprKind::CallIndirect { callee, args, .. } => {
                let head = self.expr_to_c(callee);
                let args = args
                    .iter()
                    .map(|a| self.expr_to_c(a))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("({})({})", head, args)
            }
            // 字段访问：结构体按名字；元组下标是数字串，C 不支持 `.0`，降级。
            ExprKind::Field(base, name) => {
                if name.chars().all(|c| c.is_ascii_digit()) {
                    "0".to_string()
                } else {
                    format!("({}).{}", self.expr_to_c(base), name)
                }
            }
            ExprKind::Deref(inner) => format!("(*{})", self.expr_to_c(inner)),
            ExprKind::AddrOf(inner) => format!("(&{})", self.expr_to_c(inner)),
            ExprKind::Index(base, index) => {
                format!("({})[{}]", self.expr_to_c(base), self.expr_to_c(index))
            }
            ExprKind::ArrayToSlice(inner) => self.expr_to_c(inner),
            ExprKind::Block(block) => self.block_value(block),
            ExprKind::If(cond, then_block, else_block) => {
                let c = self.expr_to_c(cond);
                let t = self.block_value(then_block);
                let e = else_block
                    .as_ref()
                    .map(|b| self.block_value(b))
                    .unwrap_or_else(|| "0".to_string());
                format!("(({}) ? ({}) : ({}))", c, t, e)
            }
            ExprKind::Array(items) => {
                // 元素类型从表达式的数组类型取；初始化器生命周期 = 所在块，
                // 用来给"数组类型的局部量"（映射成指针）赋值是安全的。
                let elem = match &expr.ty {
                    Ty::Array(inner, _) | Ty::Slice(inner, _) => self.ty_to_c(inner),
                    _ => "intptr_t".to_string(),
                };
                let items = items
                    .iter()
                    .map(|i| self.expr_to_c(i))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("(({}[]){{ {} }})", elem, items)
            }
            ExprKind::Struct(fields) => {
                // 结构体类型从表达式类型取（`ExprKind::Struct` 只存字段名/值）。
                let ty = self.ty_to_c(&expr.ty);
                let init = fields
                    .iter()
                    .map(|(name, value)| format!(".{} = {}", name, self.expr_to_c(value)))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("(({}){{ {} }})", ty, init)
            }
            // 转换：目标类型就是 `expr.ty`，直接翻成 C 的强制类型转换。
            ExprKind::Cast(inner) => {
                format!("(({})({}))", self.ty_to_c(&expr.ty), self.expr_to_c(inner))
            }
            ExprKind::Comptime(lit) => self.literal_to_c(lit),
            // 未覆盖的构造：降级成中性值，只保证 C 能编过。
            _ => "0".to_string(),
        }
    }

    /// 块的"值"（用作三元运算的操作数）：有尾表达式取尾，否则 `0`。
    fn block_value(&self, block: &HirBlock) -> String {
        match &block.tail {
            Some(tail) => self.expr_to_c(tail),
            None => "0".to_string(),
        }
    }

    /// 引用一个 `Def`：常量内联其值，其余用最终符号名。
    fn def_ref_to_c(&self, id: DefId) -> String {
        if let Some(c) = self.module.consts.get(&id) {
            return self.expr_to_c(&c.value);
        }
        match self.module.def_names.get(&id) {
            Some(name) => name.clone(),
            None => format!("def_{}", id.0),
        }
    }

    fn literal_to_c(&self, lit: &HirLiteral) -> String {
        match lit {
            HirLiteral::Int(v) => v.to_string(),
            HirLiteral::Float(f) => float_to_c(*f),
            HirLiteral::Bool(b) => b.to_string(),
            // zr 的 `char` 是 Unicode 标量值，映射成 `uint32_t`，字面量翻成码点。
            HirLiteral::Char(c) => format!("((uint32_t){})", *c as u32),
            HirLiteral::String(s) => {
                let esc = escape_c_string(s);
                format!(
                    "((zr_str){{ (const uint8_t*)\"{}\", sizeof(\"{}\") - 1 }})",
                    esc, esc
                )
            }
            // 编译期聚合值不应逃逸到运行期；真的到了这里就退化成零初始化。
            HirLiteral::Composite(_) => "{0}".to_string(),
        }
    }

    // ==================================================================
    // 类型
    // ==================================================================

    fn ty_to_c(&self, ty: &Ty) -> String {
        match ty {
            Ty::Int(bits) => match bits {
                8 => "int8_t".to_string(),
                16 => "int16_t".to_string(),
                32 => "int32_t".to_string(),
                64 => "int64_t".to_string(),
                128 => "__int128".to_string(),
                _ => "intptr_t".to_string(),
            },
            Ty::Uint(bits) => match bits {
                8 => "uint8_t".to_string(),
                16 => "uint16_t".to_string(),
                32 => "uint32_t".to_string(),
                64 => "uint64_t".to_string(),
                128 => "unsigned __int128".to_string(),
                _ => "uintptr_t".to_string(),
            },
            Ty::Float(bits) => match bits {
                32 => "float".to_string(),
                _ => "double".to_string(),
            },
            Ty::Bool => "bool".to_string(),
            Ty::Char => "uint32_t".to_string(),
            Ty::Str => "zr_str".to_string(),
            Ty::Unit | Ty::Never => "void".to_string(),
            Ty::Named(id, _) => self.named_ty_to_c(*id),
            Ty::Pointer(inner, _) | Ty::Reference(inner, _) => {
                format!("{}*", self.ty_to_c(inner))
            }
            // 数组 / 切片按指针处理（值语义的聚合在 C 里没法直接表达）。
            Ty::Array(inner, _) => format!("{}*", self.ty_to_c(inner)),
            Ty::Slice(inner, _) => format!("{}*", self.ty_to_c(inner)),
            Ty::Pin(inner) => self.ty_to_c(inner),
            // 其余（元组、函数指针、可选 / 错误联合、trait 对象……）暂未映射。
            _ => "intptr_t".to_string(),
        }
    }

    /// 命名类型 → C 类型名：结构体 / 联合体 / 枚举。载荷枚举没有 C 对应，
    /// 退化成 `intptr_t`。
    fn named_ty_to_c(&self, id: DefId) -> String {
        match self.module.type_defs.get(&id) {
            Some(HirTypeDef::Struct(s)) => format!("struct {}", s.name),
            Some(HirTypeDef::Union(u)) => format!("union {}", u.name),
            Some(HirTypeDef::Enum(e)) if enum_is_unit_only(e) => format!("enum {}", e.name),
            Some(HirTypeDef::Alias { target, .. }) => self.ty_to_c(target),
            _ => "intptr_t".to_string(),
        }
    }
}

