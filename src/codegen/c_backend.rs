//! C 后端：将 HIR 翻译为 C 翻译单元。
//!
//! 用于自举：在没有原生后端的平台上，可先编译为 C 再用系统 C 编译器编译。

use crate::typeck::hir::{
    BinaryOp, ExprKind, HirBlock, HirExpr, HirFunction, HirLiteral, HirModule, HirStmt,
    HirTypeDef, UnaryOp,
};
use std::fmt::Write;

/// C 后端输出。
pub struct CBackend;

impl CBackend {
    /// 将 HIR 模块翻译为 C 源文件文本。
    pub fn translate(module: &HirModule) -> String {
        let mut out = String::new();
        // 头文件
        out.push_str("// Generated by zr C backend\n");
        out.push_str("#include <stdint.h>\n");
        out.push_str("#include <stddef.h>\n");
        out.push_str("#include <stdbool.h>\n");
        out.push_str("#include <stdlib.h>\n");
        out.push_str("#include <string.h>\n\n");

        // 前向声明所有类型
        for td in &module.type_defs {
            Self::emit_type_forward(td, &mut out);
        }
        // 前向声明所有函数
        for func in &module.functions {
            Self::emit_func_forward(func, &mut out);
        }

        out.push('\n');

        // 类型定义
        for td in &module.type_defs {
            Self::emit_type_def(td, &mut out);
        }

        // 函数定义
        for func in &module.functions {
            Self::emit_func(func, &mut out);
        }

        out
    }

    fn emit_type_forward(td: &HirTypeDef, out: &mut String) {
        match td {
            HirTypeDef::Struct(s) => {
                let _ = writeln!(out, "struct {};", s.name);
            }
            HirTypeDef::Enum(e) => {
                let _ = writeln!(out, "enum {};", e.name);
            }
            HirTypeDef::Union(u) => {
                let _ = writeln!(out, "union {};", u.name);
            }
            HirTypeDef::Alias { .. } => {}
        }
    }

    fn emit_type_def(td: &HirTypeDef, out: &mut String) {
        match td {
            HirTypeDef::Struct(s) => {
                let _ = write!(out, "struct {} {{\n", s.name);
                for field in &s.fields {
                    let _ = writeln!(out, "    {} {};", Self::ty_to_c(&field.ty), field.name);
                }
                let _ = writeln!(out, "}};\n");
            }
            HirTypeDef::Enum(e) => {
                let _ = write!(out, "enum {} {{\n", e.name);
                for (i, v) in e.variants.iter().enumerate() {
                    let _ = writeln!(out, "    {} = {},", v.name, i);
                }
                let _ = writeln!(out, "}};\n");
            }
            HirTypeDef::Union(u) => {
                let _ = write!(out, "union {} {{\n", u.name);
                for field in &u.fields {
                    let _ = writeln!(out, "    {} {};", Self::ty_to_c(&field.ty), field.name);
                }
                let _ = writeln!(out, "}};\n");
            }
            HirTypeDef::Alias { .. } => {}
        }
    }

    fn emit_func_forward(func: &HirFunction, out: &mut String) {
        let ret = Self::ty_to_c(&func.return_type);
        let params = if func.params.is_empty() {
            "void".to_string()
        } else {
            func.params
                .iter()
                .map(|p| format!("{} {}", Self::ty_to_c(&p.ty), Self::pattern_name(&p.pattern)))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let _ = writeln!(out, "{} {}({});", ret, func.name, params);
    }

    fn emit_func(func: &HirFunction, out: &mut String) {
        let ret = Self::ty_to_c(&func.return_type);
        let params = if func.params.is_empty() {
            "void".to_string()
        } else {
            func.params
                .iter()
                .map(|p| format!("{} {}", Self::ty_to_c(&p.ty), Self::pattern_name(&p.pattern)))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let _ = writeln!(out, "{} {}({}) {{", ret, func.name, params);
        if let Some(body) = &func.body {
            Self::emit_block(body, out, 1);
        }
        let _ = writeln!(out, "}}\n");
    }

    fn emit_block(block: &HirBlock, out: &mut String, indent: usize) {
        let pad = "    ".repeat(indent);
        for stmt in &block.stmts {
            Self::emit_stmt(stmt, out, indent, &pad);
        }
        // 尾部表达式作为 return（如果类型非 unit）
        if let Some(tail) = &block.tail {
            if !Self::is_unit_expr(tail) {
                let _ = writeln!(out, "{}return {};", pad, Self::expr_to_c(tail));
            }
        }
    }

    fn emit_stmt(stmt: &HirStmt, out: &mut String, indent: usize, pad: &str) {
        match stmt {
            HirStmt::Let { ty, init, .. } => {
                let name = format!("var{}", indent);
                let ty_str = Self::ty_to_c(ty);
                if let Some(init) = init {
                    let _ = writeln!(out, "{}{} {} = {};", pad, ty_str, name, Self::expr_to_c(init));
                } else {
                    let _ = writeln!(out, "{}{} {};", pad, ty_str, name);
                }
            }
            HirStmt::Var { ty, init, .. } => {
                let name = format!("var{}", indent);
                let ty_str = Self::ty_to_c(ty);
                if let Some(init) = init {
                    let _ = writeln!(out, "{}{} {} = {};", pad, ty_str, name, Self::expr_to_c(init));
                } else {
                    let _ = writeln!(out, "{}{} {};", pad, ty_str, name);
                }
            }
            HirStmt::Expr(expr, _) => {
                let _ = writeln!(out, "{}{};", pad, Self::expr_to_c(expr));
            }
            HirStmt::Const { .. } => {}
            HirStmt::Item => {}
        }
    }

    fn is_unit_expr(expr: &HirExpr) -> bool {
        matches!(
            expr.kind,
            ExprKind::Literal(HirLiteral::Composite(ref v)) if v.is_empty()
        )
    }

    fn expr_to_c(expr: &HirExpr) -> String {
        match &expr.kind {
            ExprKind::Literal(lit) => Self::literal_to_c(lit),
            ExprKind::Local(id) => format!("local_{}", id.0),
            ExprKind::Def(id) => format!("def_{}", id.0),
            ExprKind::Binary(op, lhs, rhs) => {
                format!(
                    "({} {} {})",
                    Self::expr_to_c(lhs),
                    Self::binop_to_c(op),
                    Self::expr_to_c(rhs)
                )
            }
            ExprKind::Unary(op, operand) => {
                format!("{}{}", Self::unop_to_c(op), Self::expr_to_c(operand))
            }
            ExprKind::Assign(target, value) => {
                format!("{} = {}", Self::expr_to_c(target), Self::expr_to_c(value))
            }
            ExprKind::Call(callee, args) => {
                let args_str = args.iter().map(Self::expr_to_c).collect::<Vec<_>>().join(", ");
                format!("{}({})", Self::expr_to_c(callee), args_str)
            }
            ExprKind::MethodCall(receiver, _, args) => {
                let args_str = args.iter().map(Self::expr_to_c).collect::<Vec<_>>().join(", ");
                format!("method({}, {})", Self::expr_to_c(receiver), args_str)
            }
            ExprKind::Field(object, _) => {
                format!("{}.field", Self::expr_to_c(object))
            }
            ExprKind::Deref(inner) => format!("*({})", Self::expr_to_c(inner)),
            ExprKind::AddrOf(inner, _) => format!("&({})", Self::expr_to_c(inner)),
            ExprKind::Index(array, index) => {
                format!("{}[{}]", Self::expr_to_c(array), Self::expr_to_c(index))
            }
            ExprKind::Cast(inner, _) => Self::expr_to_c(inner),
            ExprKind::Block(block) => {
                let mut s = String::from("({ ");
                for stmt in &block.stmts {
                    if let HirStmt::Expr(e, _) = stmt {
                        s.push_str(&Self::expr_to_c(e));
                        s.push_str("; ");
                    }
                }
                if let Some(tail) = &block.tail {
                    s.push_str(&Self::expr_to_c(tail));
                    s.push_str("; ");
                }
                s.push_str("})");
                s
            }
            ExprKind::If(cond, then_branch, else_branch) => {
                let mut s = format!("(({}) ? (", Self::expr_to_c(cond));
                s.push_str(&Self::block_value(then_branch));
                s.push_str(") : (");
                if let Some(el) = else_branch {
                    s.push_str(&Self::block_value(el));
                } else {
                    s.push_str("0");
                }
                s.push_str("))");
                s
            }
            ExprKind::While(cond, body, _) => {
                let mut s = format!("while ({}) {{ ", Self::expr_to_c(cond));
                for stmt in &body.stmts {
                    if let HirStmt::Expr(e, _) = stmt {
                        s.push_str(&Self::expr_to_c(e));
                        s.push_str("; ");
                    }
                }
                s.push_str("} ");
                s
            }
            ExprKind::Loop(body) => {
                let mut s = String::from("while (1) { ");
                for stmt in &body.stmts {
                    if let HirStmt::Expr(e, _) = stmt {
                        s.push_str(&Self::expr_to_c(e));
                        s.push_str("; ");
                    }
                }
                s.push_str("} ");
                s
            }
            ExprKind::Break(_) => "break".to_string(),
            ExprKind::Return(value) => {
                if let Some(v) = value {
                    format!("return {}", Self::expr_to_c(v))
                } else {
                    "return".to_string()
                }
            }
            ExprKind::Tuple(parts) => {
                let s = parts.iter().map(Self::expr_to_c).collect::<Vec<_>>().join(", ");
                format!("({})", s)
            }
            ExprKind::Array(items, _) => {
                let s = items.iter().map(Self::expr_to_c).collect::<Vec<_>>().join(", ");
                format!("((int[]){{{}}})", s)
            }
            ExprKind::Struct(_, fields) => {
                let mut s = String::from("((struct _){");
                for (_, f) in fields {
                    s.push_str(&Self::expr_to_c(f));
                    s.push_str(", ");
                }
                s.push_str("})");
                s
            }
            _ => "0".to_string(),
        }
    }

    fn block_value(block: &HirBlock) -> String {
        if let Some(tail) = &block.tail {
            Self::expr_to_c(tail)
        } else {
            "0".to_string()
        }
    }

    fn literal_to_c(lit: &HirLiteral) -> String {
        match lit {
            HirLiteral::Int(i) => i.to_string(),
            HirLiteral::Float(f) => f.to_string(),
            HirLiteral::Bool(b) => b.to_string(),
            HirLiteral::Char(c) => format!("'{}'", c),
            HirLiteral::String(s) => format!("\"{}\"", s),
            HirLiteral::Composite(_) => "0".to_string(),
            HirLiteral::Zero(_) => "0".to_string(),
        }
    }

    fn binop_to_c(op: &BinaryOp) -> &'static str {
        match op {
            BinaryOp::Add => "+",
            BinaryOp::Sub => "-",
            BinaryOp::Mul => "*",
            BinaryOp::Div => "/",
            BinaryOp::Rem => "%",
            BinaryOp::Eq => "==",
            BinaryOp::Ne => "!=",
            BinaryOp::Lt => "<",
            BinaryOp::Le => "<=",
            BinaryOp::Gt => ">",
            BinaryOp::Ge => ">=",
            BinaryOp::And => "&&",
            BinaryOp::Or => "||",
            BinaryOp::BitAnd => "&",
            BinaryOp::BitOr => "|",
            BinaryOp::BitXor => "^",
            BinaryOp::Shl => "<<",
            BinaryOp::Shr => ">>",
            _ => "+",
        }
    }

    fn unop_to_c(op: &UnaryOp) -> &'static str {
        match op {
            UnaryOp::Neg => "-",
            UnaryOp::Not => "!",
            UnaryOp::BitNot => "~",
            UnaryOp::Deref => "*",
            UnaryOp::AddrOf => "&",
        }
    }

    fn ty_to_c(ty: &crate::typeck::hir::Ty) -> String {
        use crate::typeck::hir::Ty;
        match ty {
            Ty::Int(bits) => match bits {
                8 => "int8_t".to_string(),
                16 => "int16_t".to_string(),
                32 => "int32_t".to_string(),
                64 => "int64_t".to_string(),
                _ => "intptr_t".to_string(),
            },
            Ty::Uint(bits) => match bits {
                8 => "uint8_t".to_string(),
                16 => "uint16_t".to_string(),
                32 => "uint32_t".to_string(),
                64 => "uint64_t".to_string(),
                _ => "uintptr_t".to_string(),
            },
            Ty::Float(bits) => match bits {
                32 => "float".to_string(),
                64 => "double".to_string(),
                _ => "double".to_string(),
            },
            Ty::Bool => "bool".to_string(),
            Ty::Char => "char".to_string(),
            Ty::Str => "const char*".to_string(),
            Ty::Unit => "void".to_string(),
            Ty::Never => "void".to_string(),
            Ty::Named(_, _) => "void*".to_string(),
            Ty::Pointer(inner, _) => format!("{}*", Self::ty_to_c(inner)),
            Ty::Reference(inner, _) => format!("{}*", Self::ty_to_c(inner)),
            Ty::Array(inner, _) => format!("{}*", Self::ty_to_c(inner)),
            _ => "void*".to_string(),
        }
    }

    fn pattern_name(pattern: &crate::typeck::hir::HirPattern) -> String {
        use crate::typeck::hir::HirPattern;
        match pattern {
            HirPattern::Binding(local, _) => format!("local_{}", local.0),
            HirPattern::Tuple(inner, _) => inner
                .iter()
                .map(Self::pattern_name)
                .collect::<Vec<_>>()
                .join("_"),
            _ => "_".to_string(),
        }
    }
}
